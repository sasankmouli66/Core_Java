package com.operatiors;

public class Unirary_operratorrs {

	public static void main(String[] args) {
		int a = 8;
		int b = 5;
		
		System.out.println(a++);
		System.out.println(++a);
		System.out.println(--a);
		System.out.println(a--);
		
		System.out.println(b++);
		System.out.println(++b);
		System.out.println(b--);
		System.out.println(--b);
		
		System.out.println(a++ - --b + a--);

	}

}
